#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# newNewton - Unified Native Build Pipeline (Zero-V8, Zero-Node, Zero-Deno)
#
# Tools used:
# - jq (JSON extraction for code generation and manifest transforms)
# - esbuild (Native Go binary: /opt/homebrew/bin/esbuild or $PATH)
# - zip (Built-in macOS / Linux utility)
# ==============================================================================

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

echo "🚀 Starting newNewton Native Build Pipeline..."

# Locate standalone native esbuild binary
ESBUILD_BIN=""
if command -v esbuild >/dev/null 2>&1; then
  ESBUILD_BIN="$(command -v esbuild)"
elif [[ -x "/opt/homebrew/bin/esbuild" ]]; then
  ESBUILD_BIN="/opt/homebrew/bin/esbuild"
elif [[ -x "/usr/local/bin/esbuild" ]]; then
  ESBUILD_BIN="/usr/local/bin/esbuild"
fi

if [[ -z "$ESBUILD_BIN" ]]; then
  echo "❌ Error: Standalone native esbuild not found."
  echo "   Install it with: brew install esbuild"
  exit 1
fi

echo "  ⚡ Using native esbuild: $ESBUILD_BIN ($("$ESBUILD_BIN" --version))"

# ==============================================================================
# STEP 0: ZERO-OVERHEAD CODEGEN (Bash + jq)
# ==============================================================================
echo -e "\n⚡ Step 0: Running Zero-Overhead Codegen (JSON Specs -> JS + Swift)..."

if ! command -v jq >/dev/null 2>&1; then
  echo "❌ Error: jq is required for code generation and manifest transforms."
  exit 1
fi

DEFS="$ROOT_DIR/packages/shared-spec/definitions"
MESS_RULES="$(jq '.' "$DEFS/mess-rules.json")"
ATTENDANCE_RULES="$(jq '.' "$DEFS/attendance-rules.json")"
THEME_TOKENS="$(jq '.' "$DEFS/theme-tokens.json")"
SUPABASE_CONFIG="$(jq '.' "$DEFS/supabase-config.json")"
ALIAS_MAP="$(jq '.aliases // .exactAliases // .' "$DEFS/course-aliases.json")"
STOP_WORDS="$(jq -c '.stopWords // ["and","of","the","in","to","for","with","on","at","by","an","a"]' "$DEFS/course-aliases.json")"

swift_array() {
  jq -r '[.[] | "        " + (@json)] | join(",\n")' <<<"$1"
}

swift_dict() {
  jq -r 'to_entries | map("        " + (.key | @json) + ": " + (.value | @json)) | join(",\n")' <<<"$1"
}

COMMON_ITEMS="$(swift_array "$(jq '.commonItems' "$DEFS/mess-rules.json")")"
COMMON_KEYWORDS="$(swift_array "$(jq '.commonKeywords' "$DEFS/mess-rules.json")")"
PRACTICAL_MARKERS="$(swift_array "$(jq '.practicalMarkers' "$DEFS/attendance-rules.json")")"
COURSE_ALIASES="$(swift_dict "$ALIAS_MAP")"
BASE_DELAY="$(jq -r '.macLazySubmit.baseDelaySec' "$DEFS/supabase-config.json")"
MAX_JITTER="$(jq -r '.macLazySubmit.maxJitterSec' "$DEFS/supabase-config.json")"
TARGET_PRESETS="$(jq -r '.targetPresets | join(", ")' "$DEFS/attendance-rules.json")"
PORTAL_ORIGIN="$(jq -r '.portalOrigin | @json' "$DEFS/supabase-config.json")"
SUPABASE_URL="$(jq -r '.supabaseUrl | @json' "$DEFS/supabase-config.json")"
SUPABASE_ANON_KEY="$(jq -r '.supabaseAnonKey | @json' "$DEFS/supabase-config.json")"
SUPABASE_EDGE_URL="$(jq -r '.supabaseEdgeFunctionUrl | @json' "$DEFS/supabase-config.json")"
APP_GROUP_ID="$(jq -r '.appGroupId | @json' "$DEFS/supabase-config.json")"
MENU_REMOTE_URL="$(jq -r '.menuRemoteUrl | @json' "$DEFS/mess-rules.json")"
MENU_FALLBACK_URL="$(jq -r '.menuFallbackUrl | @json' "$DEFS/mess-rules.json")"
DEFAULT_TARGET="$(jq -r '.defaultTarget' "$DEFS/attendance-rules.json")"
ATTENDANCE_EPSILON="$(jq -r '.epsilon' "$DEFS/attendance-rules.json")"

cat > "$ROOT_DIR/extension/src/generated-specs.js" <<EOF
/**
 * AUTO-GENERATED BY build.sh — DO NOT EDIT MANUALLY.
 * Single Source of Truth: packages/shared-spec/definitions/*.json
 */

export const MESS_SPEC = $MESS_RULES;
export const MESS_RULES = MESS_SPEC;

export const ATTENDANCE_SPEC = $ATTENDANCE_RULES;
export const ATTENDANCE_RULES = ATTENDANCE_SPEC;

export const COURSE_ALIASES = $ALIAS_MAP;
export const EXACT_COURSE_ALIASES = COURSE_ALIASES;
export const STOP_WORDS = new Set($STOP_WORDS.map((w) => w.toLowerCase()));

export const THEME_TOKENS = $THEME_TOKENS;
export const PLATFORM_CONFIG = $SUPABASE_CONFIG;
export const SUPABASE_CONFIG = PLATFORM_CONFIG;

export const REMOTE_MENU_URL = MESS_SPEC.menuRemoteUrl || MESS_SPEC.remoteMenuUrl;
export const DAYS_OF_WEEK = MESS_SPEC.daysOfWeek || ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
export const DAY_SHORT_NAMES = MESS_SPEC.dayShortNames || ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
export const MEAL_WINDOWS = MESS_SPEC.meals || MESS_SPEC.mealWindows || [];
export const COMMON_ITEMS_SET = new Set((MESS_SPEC.commonItems || []).map((i) => i.toLowerCase().trim()));
export const COMMON_KEYWORDS = (MESS_SPEC.commonKeywords || []).map((k) => k.toLowerCase().trim());

export const DEFAULT_ATTENDANCE_TARGET = ATTENDANCE_SPEC.defaultTarget ?? 0.75;
export const ATTENDANCE_TARGET_OPTIONS = ATTENDANCE_SPEC.targetPresets ?? ATTENDANCE_SPEC.targetOptions ?? [0.75, 0.8, 0.85];
export const PRACTICAL_MARKERS = ATTENDANCE_SPEC.practicalMarkers ?? ['Lab', 'Practical', 'Workshop'];

export function shortenCourseName(rawName) {
  if (!rawName || typeof rawName !== 'string') return 'Course';
  const cleaned = rawName
    .replace(/^Newton School of Technology\S*\s*(?:\([^)]*\)\s*)?[-–—]\s*/i, '')
    .replace(/\s*\([^)]*\)\s*/g, ' ')
    .replace(/\s*[-–—]\s+[A-Z0-9]+$/i, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return 'Course';
  if (EXACT_COURSE_ALIASES[cleaned]) return EXACT_COURSE_ALIASES[cleaned];
  const lower = cleaned.toLowerCase();
  if (EXACT_COURSE_ALIASES[lower]) return EXACT_COURSE_ALIASES[lower];
  for (const [fullTitle, alias] of Object.entries(EXACT_COURSE_ALIASES)) {
    const targetLower = fullTitle.toLowerCase();
    if (targetLower === lower || lower.startsWith(targetLower)) return alias;
  }
  if (cleaned.length <= 10) return cleaned;
  const words = cleaned.split(/[\s&/,-]+/).filter(Boolean);
  const significant = words.filter((w) => !STOP_WORDS.has(w.toLowerCase()));
  if (significant.length >= 2) return significant.map((w) => w[0].toUpperCase()).join('');
  return cleaned.slice(0, 10).trim();
}

export function isSecondaryDish(dishName) {
  if (!dishName || typeof dishName !== 'string') return false;
  const normalized = dishName.toLowerCase().trim();
  if (COMMON_ITEMS_SET.has(normalized)) return true;
  return COMMON_KEYWORDS.some((kw) => normalized.includes(kw));
}

export function classifyDish(dishName) {
  return isSecondaryDish(dishName) ? 'side' : 'main';
}

export function classifyDishes(dishes = []) {
  const main = [];
  const side = [];
  for (const raw of dishes) {
    const item = String(raw || '').trim();
    if (!item) continue;
    (isSecondaryDish(item) ? side : main).push(item);
  }
  return { main, side };
}
EOF
echo "  ✓ Generated JS Spec: extension/src/generated-specs.js"

SWIFT_CONTENT="$(cat <<EOF
//
//  NewtonSpecs.swift
//  AUTO-GENERATED BY build.sh — DO NOT EDIT MANUALLY.
//  Single Source of Truth: packages/shared-spec/definitions/*.json
//

import Foundation

public enum NewtonSpecs {
    public static let portalOrigin = $PORTAL_ORIGIN
    public static let supabaseURL = $SUPABASE_URL
    public static let supabaseAnonKey = $SUPABASE_ANON_KEY
    public static let supabaseEdgeFunctionURL = $SUPABASE_EDGE_URL
    public static let appGroupID = $APP_GROUP_ID
    public static let menuRemoteURL = URL(string: $MENU_REMOTE_URL)!
    public static let menuFallbackURL = URL(string: $MENU_FALLBACK_URL)!
    public static let macLazyBaseDelaySec: Double = $BASE_DELAY
    public static let macLazyMaxJitterSec: Double = $MAX_JITTER

    public static func randomLazyDelaySeconds() -> Double {
        let jitter = Double.random(in: -macLazyMaxJitterSec...macLazyMaxJitterSec)
        return max(5.0, macLazyBaseDelaySec + jitter)
    }

    public static let commonItems: Set<String> = [
$COMMON_ITEMS
    ]
    public static let commonKeywords: [String] = [
$COMMON_KEYWORDS
    ]
    public static let defaultAttendanceTarget: Double = $DEFAULT_TARGET
    public static let attendanceTargetPresets: [Double] = [$TARGET_PRESETS]
    public static let attendanceEpsilon: Double = $ATTENDANCE_EPSILON
    public static let practicalMarkers: [String] = [
$PRACTICAL_MARKERS
    ]
    public static let courseAliases: [String: String] = [
$COURSE_ALIASES
    ]
}
EOF
)"

for target in \
  "$ROOT_DIR/macos/newNewton/newNewton/NewtonSpecs.swift" \
  "$ROOT_DIR/macos/newNewton/newNewtonWidgets/NewtonSpecs.swift" \
  "$ROOT_DIR/macos/Sources/Shared/NewtonSpecs.swift"; do
  mkdir -p "$(dirname "$target")"
  printf '%s\n' "$SWIFT_CONTENT" > "$target"
  echo "  ✓ Generated Swift Spec: ${target#$ROOT_DIR/}"
done

# Keep Chrome update metadata tied to the manifest version.
version="$(jq -r '.version // empty' "$ROOT_DIR/extension/manifest.json")"
[[ -n "$version" ]] || { echo "❌ extension/manifest.json must contain a version"; exit 1; }
updates="$ROOT_DIR/updates.xml"
sed -E "s/(<updatecheck[^>]*version=')[^']*(')/\1${version}\2/" "$updates" > "$updates.tmp"
mv "$updates.tmp" "$updates"
echo "  ✓ Synced updates.xml version to $version"

# ==============================================================================
# STEP 1: STAGE CHROME EXTENSION (dist/extension)
# ==============================================================================
echo -e "\n📦 Step 1: Staging Chromium extension to dist/extension..."

rm -rf dist/extension
mkdir -p dist/extension

# Copy raw source tree (excluding hidden system files)
cp -R extension/* dist/extension/
find dist/extension -name ".DS_Store" -delete

# ==============================================================================
# STEP 2: NATIVE MINIFICATION (esbuild standalone)
# ==============================================================================
echo -e "\n⚡ Step 2: Minifying JS, CSS & compacting JSON with standalone esbuild..."

# 2.1 Minify all CSS files
find dist/extension -name "*.css" | while read -r css_file; do
  orig_size=$(wc -c < "$css_file" | tr -d ' ')
  "$ESBUILD_BIN" "$css_file" --minify --allow-overwrite --outfile="$css_file"
  min_size=$(wc -c < "$css_file" | tr -d ' ')
  rel_path="${css_file#dist/extension/}"
  echo "  ✓ CSS: $rel_path ($orig_size B -> $min_size B)"
done

# 2.2 Minify all JS files
find dist/extension -name "*.js" | while read -r js_file; do
  orig_size=$(wc -c < "$js_file" | tr -d ' ')
  "$ESBUILD_BIN" "$js_file" --minify --allow-overwrite --outfile="$js_file"
  min_size=$(wc -c < "$js_file" | tr -d ' ')
  rel_path="${js_file#dist/extension/}"
  echo "  ✓ JS:  $rel_path ($orig_size B -> $min_size B)"
done

# 2.3 Sanitize manifest.json (strip local development origins & format cleanly)
jq 'if (.host_permissions | type) == "array"
    then .host_permissions |= map(select((contains("127.0.0.1") | not) and (contains("localhost") | not)))
    else .
    end' dist/extension/manifest.json > dist/extension/manifest.json.tmp
mv dist/extension/manifest.json.tmp dist/extension/manifest.json
echo "  ✓ Sanitized dist/extension/manifest.json (stripped local development origins)"

# ==============================================================================
# STEP 3: BUILD MOZILLA FIREFOX EXTENSION (dist/firefox & .xpi)
# ==============================================================================
echo -e "\n🦊 Step 3: Building Mozilla Firefox extension to dist/firefox..."

rm -rf dist/firefox
mkdir -p dist/firefox
cp -R dist/extension/* dist/firefox/

jq 'del(.key, .update_url)
    | .background = {scripts: ["src/background.js"], type: "module"}
    | .browser_specific_settings = {gecko: {id: "newnewton@newtonschool.enhancer", strict_min_version: "115.0"}}' \
    dist/firefox/manifest.json > dist/firefox/manifest.json.tmp
mv dist/firefox/manifest.json.tmp dist/firefox/manifest.json
echo "  ✓ Generated Firefox MV3 manifest.json (Gecko ID & module background)"

# Package Firefox .xpi
XPI_PATH="dist/newNewton-firefox.xpi"
rm -f "$XPI_PATH"
(cd dist/firefox && zip -qr "../../$XPI_PATH" .)
xpi_size=$(wc -c < "$XPI_PATH" | tr -d ' ')
echo "  ✓ Packaged Mozilla Firefox archive: $XPI_PATH ($xpi_size B)"

# ==============================================================================
# STEP 4: SYNC SAFARI WEB EXTENSION RESOURCES (Xcode Flat Bundle Layout)
# ==============================================================================
echo -e "\n🧭 Step 4: Syncing flattened Safari Web Extension resources to Xcode target..."

SAFARI_RES="macos/newNewton/newNewtonSafariExtension/Resources"
rm -rf "$SAFARI_RES"
mkdir -p "$SAFARI_RES"

while IFS= read -r -d '' source_file; do
  file_name="$(basename "$source_file")"
  [[ "$file_name" == .* || "$file_name" == ".DS_Store" ]] && continue
  cp "$source_file" "$SAFARI_RES/$file_name"
done < <(find dist/extension -type f -print0)

safari_manifest="$SAFARI_RES/manifest.json"
jq 'del(.key, .update_url, .declarative_net_request)
    | .permissions = ((.permissions // []) | map(select(. != "declarativeNetRequest" and . != "declarativeNetRequestWithHostAccess")) | if index("nativeMessaging") then . else . + ["nativeMessaging"] end)
    | .icons = {"16": "icon16.png", "48": "icon48.png", "128": "icon128.png"}
    | if .action then .action.default_popup = "popup.html" | .action.default_icon = {"16": "icon16.png", "48": "icon48.png", "128": "icon128.png"} else . end
    | .background = {service_worker: "background.js", scripts: ["background.js"], type: "module", persistent: false}
    | (.content_scripts // []) |= map(if .js then .js |= map(split("/")[-1]) else . end | if .css then .css |= map(split("/")[-1]) else . end)
    | (.web_accessible_resources // []) |= map(.resources = ["telemetry-blocker.js", "icon16.png", "icon48.png", "icon128.png"])' \
    "$safari_manifest" > "$safari_manifest.tmp"
mv "$safari_manifest.tmp" "$safari_manifest"

while IFS= read -r -d '' item; do
  sed -i.bak \
    -e 's#\.\./generated-specs\.js#./generated-specs.js#g' \
    -e 's#\./attendance/grouping\.js#./grouping.js#g' \
    -e 's#\./attendance/math\.js#./math.js#g' \
    -e 's#\./attendance/portal-api\.js#./portal-api.js#g' \
    -e 's#src/icons/##g' \
    -e 's#src/##g' \
    -e 's#icons/##g' "$item"
  rm -f "$item.bak"
done < <(find "$SAFARI_RES" -maxdepth 1 -type f \( -name '*.js' -o -name '*.html' \) -print0)
echo "  ✓ Synced flattened resources to ${SAFARI_RES#"$ROOT_DIR/"}"

# ==============================================================================
# STEP 4.5: PACKAGE SIGNED CHROME EXTENSION (optional local artifact)
# ==============================================================================
echo -e "\n🔐 Step 4.5: Packaging signed Chrome extension..."

CRX_KEY_PATH="${CRX_PRIVATE_KEY_PATH:-.env/crx.pem}"
CRX_PATH="dist/newNewton.crx"

if [[ -s "$CRX_KEY_PATH" ]]; then
  if ! command -v npx >/dev/null 2>&1; then
    echo "❌ Error: npx is required to package a signed CRX."
    echo "   Install Node.js, or unset CRX_PRIVATE_KEY_PATH to skip CRX packaging."
    exit 1
  fi

  npx --yes crx3 -p "$CRX_KEY_PATH" -o "$CRX_PATH" dist/extension
  crx_size=$(wc -c < "$CRX_PATH" | tr -d ' ')
  echo "  ✓ Packaged signed Chrome extension: $CRX_PATH ($crx_size B)"
else
  echo "  - No CRX key at $CRX_KEY_PATH; skipping signed Chrome package."
fi

# ==============================================================================
# STEP 5: VERIFICATION SUMMARY
# ==============================================================================
echo -e "\n🔍 Step 5: Verifying distribution integrity..."
echo "  ✓ Chrome extension:  dist/extension"
if [[ -f "$CRX_PATH" ]]; then
  echo "  ✓ Signed Chrome package: $CRX_PATH"
fi
echo "  ✓ Firefox extension: dist/firefox & $XPI_PATH"
echo "  ✓ Safari extension:  $SAFARI_RES"

echo -e "\n🎉 Native Build & Packaging Complete! (Zero-V8, Zero-Node, Zero-Deno)"
